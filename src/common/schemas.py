class UnderwriteRequest(BaseModel):
    """Incoming application from a frontend or loan origination system.

    Stated figures come from the applicant; verified figures and KYC/fraud scores come from
    the verification layer (document parsing, KYC vendor). Both are required: the engine will
    not invent verification results.
    """
    applicant_id: str = Field(..., pattern=ID_PATTERN)
    entity_type: EntityType = EntityType.INDIVIDUAL
    requested_loan_amount: float = Field(..., gt=0.0)

    stated_monthly_income: float = Field(..., ge=0.0)
    verified_monthly_income: float = Field(..., ge=0.0)
    total_monthly_debt: float = Field(..., ge=0.0)
    detected_monthly_liabilities: float | None = Field(
        default=None, ge=0.0, description="Liabilities found in documents; defaults to stated debt."
    )
    liquid_reserves: float = Field(..., ge=0.0, description="Stated liquid assets.")
    verified_liquid_reserves: float | None = Field(
        default=None, ge=0.0, description="Reserves verified from statements; defaults to stated."
    )
    stated_collateral_value: float | None = Field(default=None, ge=0.0)
    verified_collateral_value: float | None = Field(default=None, ge=0.0)

    annual_operating_income: float | None = None
    annual_debt_service: float | None = Field(default=None, ge=0.0)

    kyc_confidence_score: float = Field(..., ge=0.0, le=1.0)
    document_tampering_score: float = Field(..., ge=0.0, le=1.0)
    synthetic_voice_probability: float | None = Field(default=None, ge=0.0, le=1.0)
    pep_or_sanctions_hit: bool = False
    ubo_verified: bool = True

    anomaly_flags: list[Annotated[str, StringConstraints(max_length=200)]] = Field(
        default_factory=list, max_length=25
    )

    def to_profile(self) -> ApplicantProfile:
        return ApplicantProfile(
            applicant_id=self.applicant_id,
            entity_type=self.entity_type,
            requested_loan_amount=self.requested_loan_amount,
            stated_monthly_income=self.stated_monthly_income,
            total_monthly_debt=self.total_monthly_debt,
            liquid_assets=self.liquid_reserves,
            stated_collateral_value=self.stated_collateral_value,
            annual_operating_income=self.annual_operating_income,
            annual_debt_service=self.annual_debt_service,
        )


class LLMAdvisoryStatus(str, Enum):
    COMPLETED = "COMPLETED"
    DISABLED = "DISABLED"
    FAILED = "FAILED"


class LLMAdvisory(BaseModel):
    """Outcome of the (non-binding) LLM second opinion."""
    status: LLMAdvisoryStatus
    suggested_decision: UnderwritingDecision | None = None
    risk_factors: list[str] = Field(default_factory=list)
    escalated: bool = False
    detail: str | None = None


class DecisionRecord(BaseModel):
    """A persisted, auditable underwriting decision (the API response envelope)."""
    decision_id: str
    request_id: str | None = None
    decided_at: datetime
    decided_by: str
    decided_by_role: str
    decision_rule: str = Field(..., description="Identifier of the policy rule that set the decision")
    decision_reasons: list[str] = Field(default_factory=list)
    memo: UnderwritingMemo
    llm_advisory: LLMAdvisory
    source_document: str | None = None


class DecisionPage(BaseModel):
    items: list[DecisionRecord]
    total: int
    limit: int
    offset: int


