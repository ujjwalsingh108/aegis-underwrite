"""
This module sets up supervised fine-tuning with PEFT/LoRA so the Qwen model learns
to output structured, policy-compliant underwriting memos instead of generic conversational
prose.

This script runs strictly on GPU, utilizing FlashAttention-2, bfloat16 precision, 
and gradient checkpointing to maximize training throughput and memory efficiency.
"""

import os
from typing import Any

import torch
from datasets import load_dataset
from peft import LoraConfig, TaskType, get_peft_model
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    DataCollatorForLanguageModeling,
    Trainer,
    TrainingArguments,
)
from transformers.trainer_utils import get_last_checkpoint

from src.common.config import settings
from src.common.logger import get_logger
from src.common.prompts import to_chatml

logger = get_logger("lora_trainer")


class UnderwritingLoRATrainer:
    """Production LoRA Trainer executing strictly on GPU hardware."""
    
    def __init__(self):
        self.model_name = settings.base_model_name
        self.output_dir = settings.lora_output_dir
        
        # Initialize tokenizer and explicitly type it to bypass Pylance "Tensor" callable errors
        self.tokenizer: Any = AutoTokenizer.from_pretrained(self.model_name)
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
        self.tokenizer.padding_side = "right" # Crucial for causal LM training

    def get_lora_config(self) -> LoraConfig:
        """
        Configures PEFT adapters. 
        Targeting 'all-linear' modules instead of just q_proj/v_proj ensures 
        the model learns complex JSON schema reasoning, not just attention routing.
        """
        return LoraConfig(
            task_type=TaskType.CAUSAL_LM,
            r=16,               # Increased rank for complex JSON generation
            lora_alpha=32,      # Standard scaling (alpha = 2 * r)
            lora_dropout=0.05,
            target_modules="all-linear", # Targets q, k, v, o, gate, up, down projections
            bias="none"
        )

    def prepare_peft_model(self):
        """Loads the base model in strict GPU-only mode with FlashAttention-2."""
        if not torch.cuda.is_available():
            raise RuntimeError("CUDA GPU is required for production training. CPU fallback disabled.")

        model = AutoModelForCausalLM.from_pretrained(
            self.model_name,
            torch_dtype=torch.bfloat16,  # Modern Ampere/Hopper mixed precision
            device_map="cuda",           # Strict GPU enforcement
            attn_implementation="flash_attention_2", # Eliminates memory fragmentation during training
        )
        
        # Enable gradient checkpointing to save VRAM at the cost of slight compute overhead
        model.gradient_checkpointing_enable()
        
        lora_config = self.get_lora_config()
        peft_model = get_peft_model(model, lora_config)
        peft_model.print_trainable_parameters()
        return peft_model

    def format_prompt(self, sample: dict[str, Any]) -> str:
        """Formats the input into Qwen's native ChatML structure (shared with serving)."""
        return to_chatml(
            sample["instruction"], sample["input_context"], sample["expected_memo_json"]
        )

    def tokenize_function(self, examples: dict[str, list[Any]]) -> dict[str, torch.Tensor]:
        """Maps over the dataset, formats the prompt, and tokenizes it."""
        prompts = [
            self.format_prompt({
                "instruction": inst, 
                "input_context": ctx, 
                "expected_memo_json": memo
            }) 
            for inst, ctx, memo in zip(
                examples['instruction'], 
                examples['input_context'], 
                examples['expected_memo_json'],
                strict=True,
            )
        ]
        
        return self.tokenizer(
            prompts,
            truncation=True,
            max_length=2048,
            padding="max_length",
        )

    def train(self, train_path: str, eval_path: str):
        """Executes the LoRA training loop and saves the final adapter."""
        peft_model = self.prepare_peft_model()
        
        # Load datasets generated by the Teacher LLM
        dataset = load_dataset(
            "json", 
            data_files={"train": train_path, "eval": eval_path}
        )
        
        tokenized_datasets = dataset.map(
            self.tokenize_function, 
            batched=True, 
            remove_columns=["instruction", "input_context", "expected_memo_json"]
        )

        # Causal LM collator shifts inputs for next-token prediction
        data_collator = DataCollatorForLanguageModeling(
            tokenizer=self.tokenizer, 
            mlm=False
        )

        # Type ignore bypasses Pylance's incomplete reading of the kwargs signature
        training_args = TrainingArguments(  # type: ignore
            output_dir=self.output_dir,
            logging_dir=f"{self.output_dir}/runs",  # <--- explicitly save logs to the Modal volume # type: ignore
            per_device_train_batch_size=4,
            per_device_eval_batch_size=4,
            gradient_accumulation_steps=4,
            warmup_ratio=0.03,     # type: ignore     
            num_train_epochs=3,
            learning_rate=2e-4,
            max_steps=450,
            bf16=True,                  # Requires A10G/A100 GPUs
            logging_steps=10,
            eval_strategy="steps",      
            eval_steps=50,
            save_strategy="steps",
            save_steps=50,
            save_total_limit=2,
            load_best_model_at_end=True,
            lr_scheduler_type="cosine",
            optim="adamw_torch_fused",  # Highly optimized optimizer for Ampere GPUs
            report_to="tensorboard"     # <--- Enabled TensorBoard
        )

        trainer = Trainer(
            model=peft_model,
            args=training_args,
            train_dataset=tokenized_datasets["train"],
            eval_dataset=tokenized_datasets["eval"],
            data_collator=data_collator,
        )

        # Resume only when a checkpoint exists: resume_from_checkpoint=True raises on a fresh run.
        last_checkpoint = (
            get_last_checkpoint(self.output_dir) if os.path.isdir(self.output_dir) else None
        )
        logger.info("training_started", extra={"resume_from": last_checkpoint})

        if last_checkpoint:
            # The GPU image pins torch 2.3, which transformers refuses for torch.load (CVE-2025-32434).
            # Checkpoints are only ever read from our own Modal volume, so the check is bypassed
            # for resume. Remove this once the image moves to torch>=2.6.
            import transformers.trainer
            transformers.trainer.check_torch_load_is_safe = lambda: None    # type: ignore
        trainer.train(resume_from_checkpoint=last_checkpoint)

        logger.info("training_complete", extra={"output_dir": self.output_dir})
        # Save directly from peft_model to bypass Pylance's Optional[PreTrainedModel] warning on trainer.model
        peft_model.save_pretrained(self.output_dir)
        self.tokenizer.save_pretrained(self.output_dir)