"""
src/common/schemas.py

Centralized Pydantic schemas for strict data validation across the pipeline.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, model_validator
from src.common.config import settings

class EntityType(str, Enum):
    INDIVIDUAL = "INDIVIDUAL"
    LLC = "LLC"
    CORP = "CORP"
    TRUST = "TRUST"

class UnderwritingDecision(str, Enum):
    APPROVE = "APPROVE"
    CONDITIONAL_APPROVAL = "CONDITIONAL_APPROVAL"
    MANUAL_REVIEW = "MANUAL_REVIEW"
    REJECT_CREDIT = "REJECT_CREDIT"
    REJECT_FRAUD = "REJECT_FRAUD"

class MultimodalFraudMetrics(BaseModel):
    """Aggregated fraud confidence scores from Vision and Audio agents."""
    kyc_confidence_score: float = Field(..., description="1.0 is perfect match, 0.0 is total failure.")
    document_tampering_score: float = Field(..., description="Probability of PDF/image metadata manipulation.")
    synthetic_voice_probability: Optional[float] = Field(default=None, description="Deepfake audio probability if voice verification was used.")

class ApplicantProfile(BaseModel):
    """The stated claims provided by the applicant."""
    applicant_id: str
    entity_type: EntityType
    requested_loan_amount: float
    
    # Universal / Individual Fields
    stated_monthly_income: float
    total_monthly_debt: float
    liquid_assets: float
    stated_collateral_value: Optional[float] = None
    
    # Corporate Specific Fields (LLC, CORP, TRUST)
    annual_operating_income: Optional[float] = None
    annual_debt_service: Optional[float] = None

class ExtractedFinancialMetrics(BaseModel):
    """The verified metrics parsed deterministically from documents and AI agents."""
    verified_monthly_income: float
    detected_monthly_liabilities: float
    verified_liquid_reserves: float
    verified_collateral_value: Optional[float] = None
    
    pep_or_sanctions_hit: bool = False
    ubo_verified: bool = True
    fraud_metrics: MultimodalFraudMetrics
    
    # Resolves the Pylance Error:
    income_variance_pct: float = Field(..., description="Percentage variance between stated and verified income.")
    anomaly_flags: List[str] = Field(default_factory=list)

class AuditTrailEntry(BaseModel):
    """A timestamped, role-based ledger entry for regulatory compliance."""
    step_name: str
    agent_role: str
    status: str
    details: str

class UnderwritingMemo(BaseModel):
    """The final, immutable output generated by the AI Underwriting Engine."""
    application_id: str
    decision: UnderwritingDecision

    # Quantitative Outputs with strict mathematical bounds
    calculated_dti: Optional[float] = Field(default=None, ge=0.0)
    calculated_dscr: Optional[float] = Field(default=None, ge=0.0)
    calculated_ltv: Optional[float] = Field(default=None, ge=0.0, le=2.0)
    liquidity_runway_months: float = Field(..., ge=0.0)
    overall_fraud_probability: float = Field(default=0.0, ge=0.0, le=1.0)

    approved_loan_amount: float = Field(default=0.0, ge=0.0)
    breached_policies: List[str] = Field(default_factory=list)
    risk_factors: List[str] = Field(default_factory=list)
    required_covenants: List[str] = Field(default_factory=list)

    audit_trail: List[AuditTrailEntry] = Field(..., min_length=1)

    @model_validator(mode="after")
    def enforce_policy_consistency(self) -> "UnderwritingMemo":
        # 1. Rejected applications cannot carry an approved loan amount
        if self.decision in {UnderwritingDecision.REJECT_CREDIT, UnderwritingDecision.REJECT_FRAUD}:
            if self.approved_loan_amount > 0:
                raise ValueError(
                    f"Decision '{self.decision.value}' cannot have approved_loan_amount > 0."
                )

        # 2. High fraud probability cannot be auto-approved
        if (
            self.overall_fraud_probability > settings.max_fraud_probability
            and self.decision == UnderwritingDecision.APPROVE
        ):
            raise ValueError(
                f"Fraud probability ({self.overall_fraud_probability:.2f}) exceeds "
                f"threshold ({settings.max_fraud_probability:.2f}); cannot APPROVE."
            )

        # 3. Clean approval cannot coexist with breached policies
        if self.decision == UnderwritingDecision.APPROVE and self.breached_policies:
            raise ValueError(
                f"Cannot issue clean APPROVE with breached policies: {self.breached_policies}"
            )

        return self