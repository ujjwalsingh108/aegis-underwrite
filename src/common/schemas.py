"""
src/common/schemas.py

Centralized Pydantic schemas for strict data validation across the pipeline.
This is the single home for every data contract: engine inputs/outputs, API DTOs,
the persisted decision record, and the LoRA training sample.
"""

from datetime import datetime
from enum import Enum
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator

from src.common.config import settings

ID_PATTERN = r"^[A-Za-z0-9][A-Za-z0-9_.:\-]{0,63}$"


class EntityType(str, Enum):
    INDIVIDUAL = "INDIVIDUAL"
    LLC = "LLC"
    CORP = "CORP"
    TRUST = "TRUST"


class UnderwritingDecision(str, Enum):
    APPROVE = "APPROVE"
    CONDITIONAL_APPROVAL = "CONDITIONAL_APPROVAL"
    MANUAL_REVIEW = "MANUAL_REVIEW"
    REJECT_CREDIT = "REJECT_CREDIT"
    REJECT_FRAUD = "REJECT_FRAUD"


# Ordering from most to least favourable. Used by guardrails to compare decisions.
DECISION_SEVERITY: dict[UnderwritingDecision, int] = {
    UnderwritingDecision.APPROVE: 0,
    UnderwritingDecision.CONDITIONAL_APPROVAL: 1,
    UnderwritingDecision.MANUAL_REVIEW: 2,
    UnderwritingDecision.REJECT_CREDIT: 3,
    UnderwritingDecision.REJECT_FRAUD: 4,
}


class MultimodalFraudMetrics(BaseModel):
    """Aggregated fraud confidence scores from Vision and Audio agents."""
    kyc_confidence_score: float = Field(..., ge=0.0, le=1.0, description="1.0 is a perfect match.")
    document_tampering_score: float = Field(
        ..., ge=0.0, le=1.0, description="Probability of PDF/image metadata manipulation."
    )
    synthetic_voice_probability: float | None = Field(
        default=None, ge=0.0, le=1.0, description="Deepfake audio probability if voice was used."
    )


class ApplicantProfile(BaseModel):
    """The stated claims provided by the applicant."""
    applicant_id: str = Field(..., min_length=1, max_length=64)
    entity_type: EntityType
    requested_loan_amount: float = Field(..., ge=0.0)

    # Universal / Individual Fields
    stated_monthly_income: float = Field(..., ge=0.0)
    total_monthly_debt: float = Field(..., ge=0.0)
    liquid_assets: float = Field(..., ge=0.0)
    stated_collateral_value: float | None = Field(default=None, ge=0.0)

    # Corporate Specific Fields (LLC, CORP, TRUST). Operating income may be negative (losses).
    annual_operating_income: float | None = None
    annual_debt_service: float | None = Field(default=None, ge=0.0)


class ExtractedFinancialMetrics(BaseModel):
    """The verified metrics parsed deterministically from documents and AI agents."""
    verified_monthly_income: float = Field(..., ge=0.0)
    detected_monthly_liabilities: float = Field(..., ge=0.0)
    verified_liquid_reserves: float = Field(..., ge=0.0)
    verified_collateral_value: float | None = Field(default=None, ge=0.0)

    pep_or_sanctions_hit: bool = False
    ubo_verified: bool = True
    fraud_metrics: MultimodalFraudMetrics

    income_variance_pct: float = Field(..., description="Variance between stated and verified income.")
    anomaly_flags: list[str] = Field(default_factory=list)


class AuditTrailEntry(BaseModel):
    """A timestamped, role-based ledger entry for regulatory compliance."""
    step_name: str
    agent_role: str
    status: str
    details: str


class UnderwritingMemo(BaseModel):
    """The final, immutable output generated by the AI Underwriting Engine."""
    # Zero-debt / zero-income edge cases yield infinite ratios; emit them as "Infinity" so
    # they survive JSON round-trips (the default emits null, which breaks required fields).
    model_config = ConfigDict(ser_json_inf_nan="strings")

    application_id: str
    decision: UnderwritingDecision

    # Quantitative Outputs with strict mathematical bounds
    calculated_dti: float | None = Field(default=None, ge=0.0)
    calculated_dscr: float | None = Field(default=None, ge=0.0)
    calculated_ltv: float | None = Field(default=None, ge=0.0)
    liquidity_runway_months: float = Field(..., ge=0.0)
    overall_fraud_probability: float = Field(default=0.0, ge=0.0, le=1.0)

    approved_loan_amount: float = Field(default=0.0, ge=0.0)
    breached_policies: list[str] = Field(default_factory=list)
    risk_factors: list[str] = Field(default_factory=list)
    required_covenants: list[str] = Field(default_factory=list)

    audit_trail: list[AuditTrailEntry] = Field(default_factory=list)

    @model_validator(mode="after")
    def enforce_policy_consistency(self) -> "UnderwritingMemo":
        # 1. Rejected applications cannot carry an approved loan amount
        if self.decision in {UnderwritingDecision.REJECT_CREDIT, UnderwritingDecision.REJECT_FRAUD}:
            if self.approved_loan_amount > 0:
                raise ValueError(
                    f"Decision '{self.decision.value}' cannot have approved_loan_amount > 0."
                )

        # 2. High fraud probability cannot be auto-approved
        if (
            self.overall_fraud_probability > settings.max_fraud_probability
            and self.decision == UnderwritingDecision.APPROVE
        ):
            raise ValueError(
                f"Fraud probability ({self.overall_fraud_probability:.2f}) exceeds "
                f"threshold ({settings.max_fraud_probability:.2f}); cannot APPROVE."
            )

        # 3. Clean approval cannot coexist with breached policies
        if self.decision == UnderwritingDecision.APPROVE and self.breached_policies:
            raise ValueError(
                f"Cannot issue clean APPROVE with breached policies: {self.breached_policies}"
            )

        return self


